#!/usr/bin/env python3
"""Small zero-dependency DTCG 2025.10 token resolver and CSS exporter for this Skill.
Not a full DTCG resolver: supports local token aliases and types used in this package.
Fails on missing/circular aliases, type mismatch and incoherent theme paths.
"""
from pathlib import Path
import json, re, sys
ROOT=Path(__file__).resolve().parents[1]
TOKEN_ROOT=ROOT/'tokens'

def tokens(path):
    data=json.loads((TOKEN_ROOT/path).read_text())
    def walk(o,p=()):
        for k,v in o.items():
            if k.startswith('$'): continue
            if isinstance(v,dict) and '$value' in v:yield p+(k,),v
            elif isinstance(v,dict):yield from walk(v,p+(k,))
            else:raise ValueError(f'invalid group {p+(k,)}')
    return data,dict(walk(data))

def resolve(path,items,seen=()):
    if path in seen:raise ValueError('circular alias: '+' => '.join(('.'.join(i) for i in seen+(path,))))
    if path not in items:raise ValueError('missing token: '+'.'.join(path))
    item=items[path]
    value=item['$value']
    if isinstance(value,str) and re.fullmatch(r'\{[A-Za-z0-9_.-]+\}',value):
        target=tuple(value[1:-1].split('.'))
        resolved,rtype=resolve(target,items,seen+(path,))
        if '$type' in item and item['$type']!=rtype:raise ValueError('alias type mismatch '+'.'.join(path))
        return resolved,rtype
    typ=item.get('$type')
    if typ=='color':
        if not isinstance(value,dict) or value.get('colorSpace')!='srgb' or len(value.get('components',[]))!=3 or not all(isinstance(c,(float,int)) and 0<=c<=1 for c in value['components']):raise ValueError('bad sRGB '+'.'.join(path))
        if 'hex' not in value or not re.fullmatch(r'#[a-fA-F0-9]{6}',value['hex']):raise ValueError('missing fallback HEX '+'.'.join(path))
    elif typ in ('dimension','duration'):
        units={'dimension':('px','rem'),'duration':('ms','s')}
        if not isinstance(value,dict) or not isinstance(value.get('value'),(int,float)) or value.get('unit') not in units[typ]:raise ValueError('bad dimension/duration '+'.'.join(path))
    elif typ=='cubicBezier':
        if not isinstance(value,list) or len(value)!=4 or not all(isinstance(n,(float,int)) for n in value):raise ValueError('bad easing '+'.'.join(path))
    elif typ=='number' and not isinstance(value,(float,int)):raise ValueError('bad number '+'.'.join(path))
    elif typ=='fontFamily' and not (isinstance(value,str) or (isinstance(value,list) and all(isinstance(x,str) for x in value))):raise ValueError('bad font '+'.'.join(path))
    elif typ=='fontWeight' and not (isinstance(value,int) and 1<=value<=1000):raise ValueError('bad weight '+'.'.join(path))
    elif typ not in ('color','dimension','duration','cubicBezier','number','fontFamily','fontWeight'):raise ValueError('unsupported or missing type '+'.'.join(path))
    return value,typ

def to_css(value,typ):
    if typ=='color':
        a=value.get('alpha',1)
        if a<1:return f'rgb({" ".join(str(round(c*255)) for c in value["components"])} / {a})'
        return value['hex']
    if typ in ('dimension','duration'):return str(value['value'])+value['unit']
    if typ=='cubicBezier':return 'cubic-bezier('+','.join(str(i) for i in value)+')'
    if typ=='fontFamily':return ', '.join('"'+x+'"' if (' ' in x and not x.startswith('-')) else x for x in (value if isinstance(value,list) else [value]))
    return str(value)

allpaths=None
lines=['/* GENERATED by scripts/generate_css.py; edit tokens/*.tokens.json, not this file */']
for theme in ('light','dark'):
    data,items=tokens(theme+'.tokens.json')
    paths=set(items)
    if allpaths is not None and allpaths!=paths:raise ValueError('theme token trees differ')
    allpaths=paths
    lines.append((':root, [data-theme="light"]' if theme=='light' else '[data-theme="dark"]')+' {')
    for path in sorted(items):
        if path[0] not in ('semantic','component','motion','radius','size','type'):continue
        v,typ=resolve(path,items)
        if path[0]=='semantic':var='--ds-'+ '-'.join(path[1:])
        else:var='--ds-'+'-'.join(path)
        lines.append('  '+var+': '+to_css(v,typ)+';')
    lines.append('  color-scheme: '+theme+';')
    lines.append('}')

density,items=tokens('density.tokens.json')
for mode in ('comfortable','compact'):
    lines.append((f':root, [data-density="{mode}"]' if mode=='comfortable' else f'[data-density="{mode}"]')+' {')
    for path in sorted(items):
        if path[0]==mode:
            v,typ=resolve(path,items)
            lines.append('  --ds-density-'+''.join(('-'+x[0].lower()+x[1:] if x[0].isupper() else '-'+x) for x in path[1:]).lstrip('-')+': '+to_css(v,typ)+';')
    lines.append('}')
out=ROOT/'assets/styles/design-tokens.css';out.write_text('\n'.join(lines)+'\n')
print(f'PASS tokens: {len(allpaths)} common theme paths, {len(items)} density tokens -> {out.relative_to(ROOT)}')
